// Generates src/ctype_tables.cpp: glibc's C.UTF-8 character classes and case maps as fixed range tables, so the library
// classifies characters the way espeak-ng does on Linux (speech.c sets LC_CTYPE to C.UTF-8 and uses iswalpha etc.) without
// touching the platform's wctype at run time (Windows has a 16-bit wchar_t and a different table).
// Dev tool: run on a glibc box, commit the output.   usage: gen_ctype > src/ctype_tables.cpp
#include <clocale>
#include <cstdio>
#include <cwctype>

namespace {

constexpr unsigned MAX_CP = 0x110000;

using Pred = int ( * )( wint_t );

void emit_ranges( const char* name, Pred pred ) {
	std::printf( "const CodeRange %s[] = {\n", name );
	int col = 0;
	for ( unsigned c = 0; c < MAX_CP; ) {
		if ( !pred( c ) ) {
			++c;
			continue;
		}
		unsigned e = c;
		while ( e + 1 < MAX_CP && pred( e + 1 ) ) {
			++e;
		}
		std::printf( "%s{0x%x,0x%x},", col == 0 ? "\t" : " ", c, e );
		if ( ++col == 6 ) {
			std::printf( "\n" );
			col = 0;
		}
		c = e + 1;
	}
	std::printf( "%s};\nconst size_t %s_count = sizeof( %s ) / sizeof( %s[0] );\n\n", col ? "\n" : "", name, name, name );
}

void emit_case( const char* name, wint_t ( *fn )( wint_t ) ) {
	std::printf( "const CasePair %s[] = {\n", name );
	int col = 0;
	for ( unsigned c = 0; c < MAX_CP; ++c ) {
		const unsigned m = fn( c );
		if ( m == c ) {
			continue;
		}
		std::printf( "%s{0x%x,0x%x},", col == 0 ? "\t" : " ", c, m );
		if ( ++col == 6 ) {
			std::printf( "\n" );
			col = 0;
		}
	}
	std::printf( "%s};\nconst size_t %s_count = sizeof( %s ) / sizeof( %s[0] );\n\n", col ? "\n" : "", name, name, name );
}

} // namespace

int main() {
	if ( !std::setlocale( LC_CTYPE, "C.UTF-8" ) ) {
		std::fprintf( stderr, "no C.UTF-8 locale\n" );
		return 1;
	}
	std::printf( "// GENERATED by tools/gen_ctype.cpp from glibc's C.UTF-8 (LC_CTYPE). Do not edit.\n" );
	std::printf( "#include \"ctype_tables.h\"\n\nnamespace propan2ol::ctype_tables {\n\n" );
	emit_ranges( "alpha", iswalpha );
	emit_ranges( "space", iswspace );
	emit_ranges( "upper", iswupper );
	emit_ranges( "lower", iswlower );
	emit_ranges( "digit", iswdigit );
	emit_ranges( "punct", iswpunct );
	emit_ranges( "alnum", iswalnum );
	emit_case( "to_lower", towlower );
	emit_case( "to_upper", towupper );
	std::printf( "}  // namespace propan2ol::ctype_tables\n" );
	return 0;
}

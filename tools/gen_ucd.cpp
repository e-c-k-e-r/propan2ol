// Generates src/ucd_tables.cpp: the two ucd-tools results the espeak-ng port needs as fixed tables, so ucd-tools itself isn't
// ported: ucd_toupper / ucd_tolower (translate.c, common.c) and clause_type_from_codepoint (readclause.c:88), which reduces
// ucd_lookup_category / ucd_properties to a clause type per code point.
// Dev tool: needs the espeak-ng clone (ESPEAK_SRC, default ~/Programs/espeak-ng).   usage: tools/gen_ucd.sh > src/ucd_tables.cpp
#include <ucd/ucd.h>
#include <cstdint>
#include <cstdio>

// translate.h:211-243, the clause type constants
#define CLAUSE_OPTIONAL_SPACE_AFTER 0x00008000
#define CLAUSE_PUNCTUATION_IN_WORD 0x00100000
#define CLAUSE_SPEAK_PUNCTUATION_NAME 0x00200000
#define CLAUSE_INTONATION_FULL_STOP 0x00000000
#define CLAUSE_INTONATION_COMMA 0x00001000
#define CLAUSE_INTONATION_QUESTION 0x00002000
#define CLAUSE_INTONATION_EXCLAMATION 0x00003000
#define CLAUSE_INTONATION_NONE 0x00004000
#define CLAUSE_TYPE_NONE 0x00000000
#define CLAUSE_TYPE_CLAUSE 0x00040000
#define CLAUSE_TYPE_SENTENCE 0x00080000
#define CLAUSE_NONE ( 0 | CLAUSE_INTONATION_NONE | CLAUSE_TYPE_NONE )
#define CLAUSE_PARAGRAPH ( 70 | CLAUSE_INTONATION_FULL_STOP | CLAUSE_TYPE_SENTENCE )
#define CLAUSE_PERIOD ( 40 | CLAUSE_INTONATION_FULL_STOP | CLAUSE_TYPE_SENTENCE )
#define CLAUSE_COMMA ( 20 | CLAUSE_INTONATION_COMMA | CLAUSE_TYPE_CLAUSE )
#define CLAUSE_QUESTION ( 40 | CLAUSE_INTONATION_QUESTION | CLAUSE_TYPE_SENTENCE )
#define CLAUSE_EXCLAMATION ( 45 | CLAUSE_INTONATION_EXCLAMATION | CLAUSE_TYPE_SENTENCE )
#define CLAUSE_COLON ( 30 | CLAUSE_INTONATION_FULL_STOP | CLAUSE_TYPE_CLAUSE )
#define CLAUSE_SEMICOLON ( 30 | CLAUSE_INTONATION_COMMA | CLAUSE_TYPE_CLAUSE )

#define ESPEAKNG_CLAUSE_TYPE_PROPERTY_MASK 0xFFF0000000000000ull

// copied from readclause.c:88-137
static int clause_type_from_codepoint( uint32_t c ) {
	ucd_category cat = ucd_lookup_category( c );
	ucd_property props = ucd_properties( c, cat );
	switch ( props & ESPEAKNG_CLAUSE_TYPE_PROPERTY_MASK ) {
	case ESPEAKNG_PROPERTY_FULL_STOP: return CLAUSE_PERIOD;
	case ESPEAKNG_PROPERTY_FULL_STOP | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER: return CLAUSE_PERIOD | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_QUESTION_MARK: return CLAUSE_QUESTION;
	case ESPEAKNG_PROPERTY_QUESTION_MARK | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER: return CLAUSE_QUESTION | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_QUESTION_MARK | ESPEAKNG_PROPERTY_PUNCTUATION_IN_WORD: return CLAUSE_QUESTION | CLAUSE_PUNCTUATION_IN_WORD;
	case ESPEAKNG_PROPERTY_EXCLAMATION_MARK: return CLAUSE_EXCLAMATION;
	case ESPEAKNG_PROPERTY_EXCLAMATION_MARK | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER: return CLAUSE_EXCLAMATION | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_EXCLAMATION_MARK | ESPEAKNG_PROPERTY_PUNCTUATION_IN_WORD: return CLAUSE_EXCLAMATION | CLAUSE_PUNCTUATION_IN_WORD;
	case ESPEAKNG_PROPERTY_COMMA: return CLAUSE_COMMA;
	case ESPEAKNG_PROPERTY_COMMA | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER: return CLAUSE_COMMA | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_COLON: return CLAUSE_COLON;
	case ESPEAKNG_PROPERTY_COLON | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER: return CLAUSE_COLON | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_SEMI_COLON:
	case ESPEAKNG_PROPERTY_EXTENDED_DASH: return CLAUSE_SEMICOLON;
	case ESPEAKNG_PROPERTY_SEMI_COLON | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER:
	case ESPEAKNG_PROPERTY_QUESTION_MARK | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER | ESPEAKNG_PROPERTY_INVERTED_TERMINAL_PUNCTUATION:
	case ESPEAKNG_PROPERTY_EXCLAMATION_MARK | ESPEAKNG_PROPERTY_OPTIONAL_SPACE_AFTER | ESPEAKNG_PROPERTY_INVERTED_TERMINAL_PUNCTUATION:
		return CLAUSE_SEMICOLON | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_ELLIPSIS: return CLAUSE_SEMICOLON | CLAUSE_SPEAK_PUNCTUATION_NAME | CLAUSE_OPTIONAL_SPACE_AFTER;
	case ESPEAKNG_PROPERTY_PARAGRAPH_SEPARATOR: return CLAUSE_PARAGRAPH;
	}
	return CLAUSE_NONE;
}

namespace {

void emit_case( const char* name, codepoint_t ( *fn )( codepoint_t ) ) {
	std::printf( "const CasePair %s[] = {\n", name );
	int col = 0;
	for ( unsigned c = 0; c < 0x110000; ++c ) {
		const unsigned m = fn( c );
		if ( m == c ) {
			continue;
		}
		std::printf( "%s{0x%x,0x%x},", col == 0 ? "\t" : " ", c, m );
		if ( ++col == 6 ) {
			std::printf( "\n" );
			col = 0;
		}
	}
	std::printf( "%s};\nconst size_t %s_count = sizeof( %s ) / sizeof( %s[0] );\n\n", col ? "\n" : "", name, name, name );
}

} // namespace

int main() {
	std::printf( "// GENERATED by tools/gen_ucd.cpp from espeak-ng 1.52.0's ucd-tools. Do not edit.\n" );
	std::printf( "#include \"ucd_tables.h\"\n\nnamespace propan2ol::ucd_tables {\n\n" );
	emit_case( "ucd_upper", ucd_toupper );
	emit_case( "ucd_lower", ucd_tolower );
	std::printf( "const ClauseType clause_types[] = {\n" );
	int col = 0;
	for ( unsigned c = 0; c < 0x110000; ++c ) {
		const int t = clause_type_from_codepoint( c );
		if ( t == CLAUSE_NONE ) {
			continue;
		}
		std::printf( "%s{0x%x,0x%x},", col == 0 ? "\t" : " ", c, t );
		if ( ++col == 6 ) {
			std::printf( "\n" );
			col = 0;
		}
	}
	std::printf( "%s};\nconst size_t clause_types_count = sizeof( clause_types ) / sizeof( clause_types[0] );\n\n", col ? "\n" : "" );
	std::printf( "}  // namespace propan2ol::ucd_tables\n" );
	return 0;
}
